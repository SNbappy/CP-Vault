const int N = 1e5 + 5;
vector<int> adj[N];
bool visited[N];

void dfs(int u) {
    visited[u] = true;
    cout << u << " ";
    for (int v: adj[u]) {
        if (!visited[v]) {
            dfs(v);
        }
    }
}

